/* Shared server components for practice listings and test pages */
import Link from 'next/link';
import { notFound } from 'next/navigation';
import { listening, listeningSets, reading, readingSets } from '@/content';
import { SECTION_NAV } from '@/lib/nav';
import type { TestSet } from '@/lib/types';
import { PageHeader } from './ui';
import { ProgressBadge, SubNav } from './client-ui';
import TestRunner from './TestRunner';

type RL = 'reading' | 'listening';
const cap = (s: string) => s[0].toUpperCase() + s.slice(1);
const setsOf = (skill: RL) => (skill === 'reading' ? readingSets : listeningSets);
const typeName = (skill: RL, s: TestSet) => (skill === 'reading' ? reading : listening).types.find(t => t.id === s.type)?.name || (s.type === 'gt' ? 'General Training' : 'Mixed question types');

export function SetCard({ skill, s }: { skill: RL; s: TestSet }) {
  return (
    <Link className={`tile c-${skill}`} href={`/practice/${skill}/${s.id}`}>
      <h3>{s.title}</h3>
      <p>{typeName(skill, s)}</p>
      <div className="meta">{s.level && <span className="badge">{s.level}</span>}{s.time ? <span className="badge">{s.time} min</span> : null}{s.part ? <span className="badge">Part {s.part}</span> : null}<ProgressBadge id={s.id} /></div>
    </Link>
  );
}

export function PracticeList({ skill }: { skill: RL }) {
  const sets = setsOf(skill);
  const groups = skill === 'listening'
    ? [1, 2, 3, 4].map(p => [`Part ${p}`, sets.filter(s => s.part === p)] as [string, TestSet[]])
    : [['By question type', sets.filter(s => !['mixed', 'gt'].includes(s.type))], ['Full-length passages (mixed question types)', sets.filter(s => s.type === 'mixed')], ['General Training', sets.filter(s => s.type === 'gt')]] as [string, TestSet[]][];
  return (
    <>
      <PageHeader crumbs={[['Practice', '/practice'], [cap(skill)]]} title={`${cap(skill)} practice`} />
      <SubNav items={SECTION_NAV.practice} />
      {skill === 'listening'
        ? <div className="callout"><strong>How the audio works</strong>Recordings are generated by your browser&apos;s text-to-speech with a female and a male voice (Chrome, Edge and Safari have the best voices). Tick &quot;Exam mode&quot; to hear each recording only once, as in the real test.</div>
        : <div className="callout"><strong>Exam conditions</strong>Start the timer, highlight key words in the passage, and don&apos;t look at explanations until you have checked your answers.</div>}
      {groups.filter(([, g]) => g.length).map(([h, g]) => (
        <section key={h}><h2>{h}</h2><div className="grid">{g.map(s => <SetCard key={s.id} skill={skill} s={s} />)}</div></section>
      ))}
      <div className="btn-row"><Link className="btn" href={`/mock-tests/${skill}-1`}>Take the full {cap(skill)} mock test →</Link></div>
    </>
  );
}

export function PracticeTest({ skill, id }: { skill: RL; id: string }) {
  const sets = setsOf(skill);
  const idx = sets.findIndex(s => s.id === id), s = sets[idx];
  if (!s) notFound();
  const guide = (skill === 'reading' ? reading : listening).types.find(t => t.id === s.type);
  const next = sets[idx + 1];
  return (
    <>
      <PageHeader crumbs={[['Practice', '/practice'], [cap(skill), `/practice/${skill}`], [s.title]]} title={s.title}>
        <div className="btn-row" style={{ marginTop: 0 }}>
          <span className="badge accent">{typeName(skill, s)}</span>{s.level && <span className="badge">{s.level}</span>}
          {guide && <Link className="btn small soft" href={`/${skill}/${guide.id}`}>Review the strategy first</Link>}
        </div>
      </PageHeader>
      <TestRunner set={s} skill={skill} />
      {next && <div className="btn-row" style={{ justifyContent: 'flex-end' }}><Link className="btn soft" href={`/practice/${skill}/${next.id}`}>Next set: {next.title} →</Link></div>}
    </>
  );
}

export const setParams = (skill: RL) => setsOf(skill).map(s => ({ id: s.id }));
export const setTitle = (skill: RL, id: string) => setsOf(skill).find(s => s.id === id)?.title || cap(skill) + ' practice';
