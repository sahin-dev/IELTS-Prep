'use client';
import { useEffect, useMemo, useRef, useState } from 'react';
import type { ScriptLine } from '@/lib/types';
import { pickVoice, splitSentences, stopSpeech, ttsSupported, whenVoices } from '@/lib/tts';
import { Store } from '@/lib/storage';

interface Item { li: number; text: string; pause?: number; g: 'f' | 'm'; narrator: boolean }

function buildQueue(script: ScriptLine[]): Item[] {
  const q: Item[] = [];
  script.forEach((l, li) => {
    if (l.pause) q.push({ li, text: l.t, pause: l.pause, g: 'f', narrator: true });
    else splitSentences(l.t).forEach(s => q.push({ li, text: s, g: l.g || 'f', narrator: !l.s }));
  });
  return q;
}

export default function ListeningPlayer({ script, onLine, examDefault = false }: { script: ScriptLine[]; onLine?: (i: number) => void; examDefault?: boolean }) {
  const queue = useMemo(() => buildQueue(script), [script]);
  const [supported, setSupported] = useState(true);
  const [voices, setVoices] = useState<SpeechSynthesisVoice[]>([]);
  const [vf, setVf] = useState('');
  const [vm, setVm] = useState('');
  const [rate, setRate] = useState(0.95);
  const [exam, setExam] = useState(examDefault);
  const [state, setState] = useState<'idle' | 'playing' | 'paused'>('idle');
  const [played, setPlayed] = useState(false);
  const [status, setStatus] = useState('Press Play. Audio is generated by your browser\'s text-to-speech. Read the questions first, as you would in the real test.');
  const [progress, setProgress] = useState(0);
  const run = useRef({ idx: 0, gen: 0, timer: undefined as ReturnType<typeof setInterval> | undefined, playing: false });
  const cfg = useRef({ vf, vm, rate, voices });
  cfg.current = { vf, vm, rate, voices };
  const lineCb = useRef(onLine);
  lineCb.current = onLine;

  useEffect(() => {
    setSupported(ttsSupported());
    setRate(Store.get('voice:rate', 0.95));
    whenVoices(v => {
      setVoices(v);
      const f = v.find(x => x.name === Store.get<string | null>('voice:f', null)) || pickVoice(v, 'f');
      setVf(f?.name || '');
      const savedM = v.find(x => x.name === Store.get<string | null>('voice:m', null));
      const m = savedM || v.find(x => x !== f && /male|david|george|ryan|guy|daniel|james|thomas|brian/i.test(x.name) && !/female/i.test(x.name)) || v.find(x => x !== f) || f;
      setVm(m?.name || '');
    });
    const r = run.current;
    return () => { r.gen++; r.playing = false; clearInterval(r.timer); stopSpeech(); };
  }, []);

  function next() {
    const r = run.current, my = r.gen;
    if (r.idx >= queue.length) {
      r.playing = false; setState('idle'); setPlayed(true); setProgress(100); lineCb.current?.(-1);
      setStatus('Finished. Check your answers, then open the transcript to review.');
      return;
    }
    const item = queue[r.idx];
    setProgress(Math.round((r.idx / queue.length) * 100));
    lineCb.current?.(item.li);
    if (item.pause) {
      let s = item.pause;
      setStatus(`${item.text} (${s}s)`);
      r.timer = setInterval(() => {
        if (my !== r.gen) return clearInterval(r.timer);
        s--; setStatus(`${item.text} (${s}s)`);
        if (s <= 0) { clearInterval(r.timer); r.idx++; next(); }
      }, 1000);
      return;
    }
    setStatus(`Playing... (${Math.round((r.idx / queue.length) * 100)}%)`);
    const u = new SpeechSynthesisUtterance(item.text);
    const name = item.g === 'm' ? cfg.current.vm : cfg.current.vf;
    const voice = cfg.current.voices.find(v => v.name === name);
    if (voice) u.voice = voice;
    u.rate = cfg.current.rate;
    u.pitch = item.narrator ? 1 : item.g === 'm' ? 0.9 : 1.08;
    const done = () => { if (my !== r.gen || !r.playing) return; r.idx++; setTimeout(next, 250); };
    u.onend = done; u.onerror = done;
    speechSynthesis.speak(u);
  }

  function play() {
    const r = run.current;
    if (r.playing || (exam && played)) return;
    if (r.idx >= queue.length) r.idx = 0;
    r.playing = true; r.gen++; setState('playing');
    stopSpeech();
    next();
  }
  function pause() {
    const r = run.current;
    if (!r.playing) return;
    if (exam) { setStatus('Pausing is disabled in exam mode.'); return; }
    r.playing = false; r.gen++; clearInterval(r.timer); stopSpeech(); setState('paused');
    setStatus('Paused. Press Play to continue from the current sentence.');
  }
  function restart() {
    if (exam && played) { setStatus('Exam mode: the recording can only be played once. Untick exam mode to replay.'); return; }
    const r = run.current;
    r.playing = false; r.gen++; clearInterval(r.timer); stopSpeech(); r.idx = 0;
    setState('idle'); setProgress(0); lineCb.current?.(-1); setStatus('Ready. Press Play to start from the beginning.');
  }

  if (!supported) {
    return <div className="callout warn"><strong>Audio not supported</strong>Your browser does not support speech synthesis. Use Chrome, Edge or Safari, or read the transcript aloud with a partner.</div>;
  }
  const opts = voices.map(v => <option key={v.name} value={v.name}>{v.name} ({v.lang})</option>);
  return (
    <div className="player">
      <div className="controls">
        <button className="btn small" onClick={play} disabled={state === 'playing' || (exam && played)}>▶ Play</button>
        <button className="btn small soft" onClick={pause} disabled={state !== 'playing'}>❚❚ Pause</button>
        <button className="btn small soft" onClick={restart}>■ Restart</button>
        <label className="small">Speed <select value={rate} onChange={e => { setRate(+e.target.value); Store.set('voice:rate', +e.target.value); }}>
          {[0.8, 0.9, 0.95, 1, 1.1].map(x => <option key={x} value={x}>{x}</option>)}
        </select></label>
        <label className="small"><input type="checkbox" checked={exam} onChange={e => setExam(e.target.checked)} /> Exam mode (play once, no pausing)</label>
      </div>
      <div className="controls small" style={{ marginTop: 8 }}>
        <label>Female voice <select value={vf} onChange={e => { setVf(e.target.value); Store.set('voice:f', e.target.value); }}>{opts}</select></label>
        <label>Male voice <select value={vm} onChange={e => { setVm(e.target.value); Store.set('voice:m', e.target.value); }}>{opts}</select></label>
      </div>
      <div className="progress"><div style={{ width: progress + '%' }} /></div>
      <div className="status" aria-live="polite">{status}</div>
    </div>
  );
}
